#!/usr/bin/env python3
"""One table of all 146 concepts: meaning, group, whether the rule reads the hand, how often it is true and
hand evidence on held-out decisions, and the independent model's F1 and dependence on it (--tex: the thesis
table)."""
from __future__ import annotations

import argparse
import dis
import json
import multiprocessing as mp
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

import numpy as np

EVAL = REPO / "runs" / "evaluation"


def vocabulary_sections():
    """{concept: section title}, from the comment that heads each group in vocabulary.py."""
    src = (REPO / "concepts" / "vocabulary.py").read_text()
    body = src[src.index("HARD_STATE_CONCEPTS = ["):src.index("]\n\nSAYC_CONCEPTS")]
    section, fresh, out = "", True, {}
    for line in body.splitlines()[1:]:
        s = line.strip()
        if s.startswith("#"):
            if fresh:  # first line of a comment block names the section
                section = s.lstrip("# ").rstrip(" --").split(" -- ")[0].split(" (")[0].split(". ")[0].rstrip(".:")
                fresh = False
        elif s.startswith('"'):
            out[s.strip('",')] = section
            fresh = True
    return out


_LOADS = ("LOAD_FAST", "LOAD_FAST_CHECK", "LOAD_DEREF", "LOAD_CLOSURE", "MAKE_CELL")


def _uses_hand_arg(fn) -> bool:
    """Static, from the bytecode: does the predicate read its second argument (the
    HandFeatures)? Covers inline lambdas, named predicates and generator expressions
    over the hand (a closure over `h`)."""
    code = getattr(fn, "__code__", None)
    if code is None or code.co_argcount < 2:
        return True  # unknown signature: do not claim it ignores the hand
    hand = code.co_varnames[1]
    return any(ins.opname in _LOADS and ins.argval == hand for ins in dis.get_instructions(code))


def _always_false(fn) -> bool:
    """`lambda a, h: False` -- a retired concept's rule."""
    ins = [i for i in dis.get_instructions(fn) if i.opname not in ("RESUME", "NOP")]
    return ((len(ins) == 2 and ins[0].opname == "LOAD_CONST" and ins[0].argval is False
             and ins[1].opname == "RETURN_VALUE")
            or (len(ins) == 1 and ins[0].opname == "RETURN_CONST" and ins[0].argval is False))


def rule_reads_hand(rule) -> bool:
    """Static: does any predicate of the rule look at the hand?"""
    return any(_uses_hand_arg(fn) for fn in rule.holds_if)


def _hand_dependence(rows):
    """For each decision (obs bits, action index): which concepts are true and which
    are hand-dependent there (probe hands, as nlg.explanation_inputs does)."""
    from concepts import HARD_STATE_CONCEPTS, AuctionContext, create_sayc_state_authority, decode_hand
    from concepts.auction_obs import auction_from_obs
    from nlg.explanation_inputs import _probe_values
    from evaluation.common import BIDS
    auth = create_sayc_state_authority()
    true_n = np.zeros(len(HARD_STATE_CONCEPTS), np.int64)
    dep_n = np.zeros(len(HARD_STATE_CONCEPTS), np.int64)
    for obs, action in rows:
        calls, dealer = auction_from_obs(obs)
        bid = BIDS[int(action)]
        own = auth.classify(AuctionContext(bids=calls, bid=bid, dealer=dealer), decode_hand(obs))
        probe = _probe_values(tuple(calls), bid, dealer)
        for k, name in enumerate(HARD_STATE_CONCEPTS):
            if own[name]:
                true_n[k] += 1
                if len(probe.get(name, frozenset()) | {True}) > 1:
                    dep_n[k] += 1
    return true_n, dep_n


# the group names of the thesis's vocabulary table (evaluation.common.concept_category)
GROUP = {"convention": "Conventions", "strength": "Strength", "length / strain": "Length, suit",
         "fit / support": "Fit, support", "competitive": "Competition", "opening": "Openings",
         "auction structure": "Structure", "pass / double": "Pass, double", "strain": "Descriptor"}


def _tex(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("<", r"$<$"), (">", r"$>$"), ("~", r"\textasciitilde{}")):
        s = s.replace(a, b)
    return s


def write_tex(path: Path, rows, n: int, deals: int, counts: dict) -> None:
    """The 146 concepts as a longtable for the thesis appendix."""
    L = ["% Generated by scripts/concept_catalogue.py --tex -- do not edit by hand.",
         "\\begin{longtable}{@{}r >{\\raggedright\\arraybackslash}p{4.2cm} >{\\raggedright\\arraybackslash}p{4.6cm} l c r@{}}",
         f"\\caption[The 146 concepts]{{The concept vocabulary in checkpoint order "
         f"with each concept's meaning (\\texttt{{concepts/vocabulary.py}}) and group (Table~\\ref{{tab:vocabulary}}). Hand: whether the rule has a condition on the hand "
         f"({counts['yes']} rules), only on the auction and the bid ({counts['no']}), or is retired and never "
         f"true ({counts['never']}). True: share of {n:,} held-out WBridge5 decisions ({deals:,} test deals) "
         f"at which the concept holds for WBridge5's bid.}}",
         "\\label{tab:concept_list}\\\\",
         "\\toprule", "\\# & Concept & Meaning & Group & Hand & True (\\%) \\\\", "\\midrule", "\\endfirsthead",
         "\\toprule", "\\# & Concept & Meaning & Group & Hand & True (\\%) \\\\", "\\midrule", "\\endhead",
         "\\bottomrule", "\\endlastfoot"]
    for k, name, gloss, group, reads, pct, _dep in rows:
        hand = {"yes": "yes", "no": "no", "never": "retired"}[reads]
        tt = _tex(name).replace("\\_", "\\_\\allowbreak{}")  # long names may break at underscores
        L.append(f"{k} & \\texttt{{{tt}}} & {_tex(gloss)} & {GROUP.get(group, group)} & "
                 f"{hand} & {pct:.2f} \\\\")
    L.append("\\end{longtable}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n")
    print(f"[catalogue] LaTeX longtable -> {path}")


def _load(path: Path):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--deals", type=int, default=600, help="held-out test deals to measure on")
    ap.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    ap.add_argument("--out", default=str(REPO / "notes" / "concept_catalogue.md"))
    ap.add_argument("--tex", default=None,
                    help="also write the list as a LaTeX longtable (the thesis appendix), e.g. concept_list.tex")
    args = ap.parse_args()

    from concepts import HARD_STATE_CONCEPTS, gloss_for_concept
    from concepts.rules import build_sayc_state_rules
    from evaluation.common import concept_category, load_test_split

    rules = {r.name: r for r in build_sayc_state_rules()}
    sections = vocabulary_sections()
    pos = load_test_split(max_deals=args.deals)
    rows = list(zip(pos.obs, pos.action))
    chunks = [rows[i::args.workers] for i in range(args.workers)]
    with mp.get_context("fork").Pool(args.workers) as pool:
        parts = pool.map(_hand_dependence, chunks)
    true_n = sum(p[0] for p in parts)
    dep_n = sum(p[1] for p in parts)
    n = len(rows)

    quality = _load(EVAL / "concepts" / "concept_quality.json") or {}
    f1_own = (quality.get("SL independent") or {}).get("self", {}).get("per_concept", {})
    infl = _load(EVAL / "influence" / "SL_independent__test.json") or {}
    kl = {c["name"]: c for c in infl.get("per_concept", [])}

    lines = [
        "# Concept catalogue",
        "",
        f"All {len(HARD_STATE_CONCEPTS)} concepts of `concepts/vocabulary.py`, in vocabulary order (= the column "
        "order of every checkpoint's `hard_state_head`). Generated by `scripts/concept_catalogue.py` "
        "-- re-run it after a rule change instead of editing this file.",
        "",
        "Columns:",
        "- **section**: the vocabulary comment the concept sits under; **group**: the coarse group "
        "the thesis figures use (`evaluation.common.concept_category`).",
        "- **reads hand**: the rule has at least one condition on the hand (static check of the rule's "
        "predicates). `never` = a retired concept whose rule is always false (kept because the order is "
        "load-bearing).",
        f"- **% true**: share of {n:,} held-out WBridge5 decisions ({args.deals} test deals) where the "
        "concept holds for WBridge5's call.",
        "- **hand evidence**: of those, the share where the concept depends on the hand (re-classifying "
        "with the 48 probe hands of `nlg.explanation_inputs` changes it). 0% = it only restates the call, so the "
        "explanations never cite it as a reason.",
        "- **F1 (own call)**: test-split F1 of the SL independent model's concept head against the rules "
        "applied to the model's own call (`runs/evaluation/concepts/concept_quality.json`, support in "
        "brackets); **KL if zeroed**: mean KL(pi || pi with the concept set to 0) of the same model, in "
        "nats (`runs/evaluation/influence/SL_independent__test.json`). Empty when those files are missing.",
        "",
        "| # | concept | meaning | section | group | reads hand | % true | hand evidence | F1 (own call) | KL if zeroed |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    counts = {"yes": 0, "no": 0, "never": 0}
    tex_rows = []
    for k, name in enumerate(HARD_STATE_CONCEPTS):
        rule = rules[name]
        # bid_is_splinter's own rule is a placeholder: SaycStateAuthority.classify sets it to the
        # union of its two hand-reading sub-types (void / singleton splinter)
        retired = len(rule.holds_if) == 1 and _always_false(rule.holds_if[0]) and name != "bid_is_splinter"
        reads = "never" if retired else ("yes" if (rule_reads_hand(rule) or name == "bid_is_splinter") else "no")
        counts[reads] += 1
        pct = 100 * true_n[k] / max(n, 1)
        dep = f"{100 * dep_n[k] / true_n[k]:.0f}%" if true_n[k] else "-"
        f = f1_own.get(name)
        f1 = f"{f['f1']:.3f} ({f['support']})" if f and f.get("support") else "-"
        kz = kl.get(name, {}).get("kl_zero")
        kls = f"{kz:.4f}" if kz is not None else "-"
        lines.append(f"| {k} | `{name}` | {gloss_for_concept(name)} | {sections.get(name, '')} | "
                     f"{concept_category(name)} | {reads} | {pct:.2f}% | {dep} | {f1} | {kls} |")
        tex_rows.append((k, name, gloss_for_concept(name), concept_category(name), reads, pct,
                         (100 * dep_n[k] / true_n[k]) if true_n[k] else None))

    lines += ["", f"Rules with a condition on the hand: {counts['yes']}; decided by the auction and the call "
              f"alone: {counts['no']}; retired (always false): {counts['never']}. "
              f"{sum(1 for k in range(len(HARD_STATE_CONCEPTS)) if true_n[k] == 0)} concepts were never true "
              f"on these {n:,} decisions.", ""]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines))
    if args.tex:
        write_tex(Path(args.tex).expanduser(), tex_rows, n, args.deals, counts)
    print(f"[catalogue] {len(HARD_STATE_CONCEPTS)} concepts, {n:,} decisions -> {args.out}")


if __name__ == "__main__":
    main()
